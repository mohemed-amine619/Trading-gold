"""
core/strategy/library/events.py — economic-event strategies.

Event times come from ``cfg.events`` (a tuple of ``(utc datetime, title)``; the
live bot fills it from core/risk/news_calendar.py) plus Non-Farm Payrolls, which
are generated by rule (first Friday of the month, 08:30 New York) so they also
exist in historical bars. With no event in the data a strategy simply never
fires, and the proof gate then keeps it silent.

Two mechanics, applied per event family:
* breakout: the first close beyond the hour-before-release range, within 2 hours;
* reversal: a spike of 1.5+ ATR beyond that range that closes back inside within
  8 bars -> fade it.

Note the bot's own news blackout blocks NEW entries around major releases. While
it is on, these strategies can be proven but their votes cannot open a trade
during the blackout; they act on the bars after it.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Iterable, List, Sequence, Tuple

import numpy as np
import pandas as pd

from core.strategy.library._common import EPS, ohlc

_NFP = re.compile(r"non-?farm|\bNFP\b|employment situation", re.I)
_CPI = re.compile(r"\bCPI\b|consumer price", re.I)
_FOMC = re.compile(r"\bFOMC\b|federal funds|fed(eral)? (interest )?rate|powell|fed chair", re.I)
_RATES = re.compile(r"rate decision|interest rate|federal funds|monetary policy|\bECB\b|\bBOE\b|\bBOJ\b|cash rate", re.I)


def nfp_times(start: pd.Timestamp, end: pd.Timestamp) -> List[pd.Timestamp]:
    """First Friday of each month, 08:30 New York, as naive UTC timestamps."""
    out = []
    month = pd.Timestamp(year=start.year, month=start.month, day=1)
    while month <= end:
        first_friday = month + pd.Timedelta(days=(4 - month.weekday()) % 7)
        y = first_friday.year
        march1 = pd.Timestamp(year=y, month=3, day=1)
        dst_start = march1 + pd.Timedelta(days=(6 - march1.weekday()) % 7 + 7)
        nov1 = pd.Timestamp(year=y, month=11, day=1)
        dst_end = nov1 + pd.Timedelta(days=(6 - nov1.weekday()) % 7)
        offset = 4 if dst_start <= first_friday < dst_end else 5
        out.append(first_friday + pd.Timedelta(hours=8 + offset, minutes=30))
        month = (month + pd.offsets.MonthBegin(1)).normalize()
    return out


def _event_times(df: pd.DataFrame, cfg, pattern) -> List[pd.Timestamp]:
    """UTC-naive event times of one family that fall inside the frame."""
    events: Sequence[Tuple[datetime, str]] = tuple(getattr(cfg, "events", ()) or ())
    off = pd.Timedelta(hours=float(getattr(cfg, "server_utc_offset", 0.0)))
    idx = df.index.tz_convert(None) if df.index.tz is not None else df.index
    start, end = idx[0] - off, idx[-1] - off
    times = []
    for when, title in events:
        if pattern is not None and not pattern.search(title or ""):
            continue
        ts = pd.Timestamp(when)
        ts = ts.tz_convert(None) if ts.tzinfo is not None else ts
        if start <= ts <= end:
            times.append(ts)
    if pattern is None or pattern is _NFP:
        times.extend(t for t in nfp_times(start, end) if start <= t <= end)
    # convert to the data's clock, de-duplicated
    return sorted({(t + off).floor("min") for t in times})


def _event_signals(df, atr, cfg, pattern, mode: str) -> np.ndarray:
    o, h, l, c = ohlc(df)
    n = len(c)
    sig = np.zeros(n, dtype=np.int8)
    idx = df.index.tz_convert(None) if df.index.tz is not None else df.index
    bar = (idx[1] - idx[0]) if n > 1 else pd.Timedelta(minutes=15)
    for ev in _event_times(df, cfg, pattern):
        first = int(np.searchsorted(idx.values, np.datetime64(ev - bar), side="right"))
        # first bar whose interval contains or follows the release
        if first >= n:
            continue
        pre = (idx >= ev - pd.Timedelta(hours=1)) & (idx < ev - bar + pd.Timedelta(seconds=1)) & (idx < idx[first])
        if pre.sum() < 2:
            continue
        hi, lo = h[pre].max(), l[pre].min()
        a = atr[first - 1] if first > 0 else np.nan
        if not np.isfinite(a) or a <= 0:
            continue
        stop = min(n, first + max(1, int(pd.Timedelta(hours=2) / bar)))
        if mode == "breakout":
            for t in range(first, stop):
                if c[t] > hi:
                    sig[t] = 1; break
                if c[t] < lo:
                    sig[t] = -1; break
        else:
            spiked = 0
            for t in range(first, min(n, first + 8)):
                if not spiked:
                    if h[t] > hi + 1.5 * a:
                        spiked = 1
                    elif l[t] < lo - 1.5 * a:
                        spiked = -1
                if spiked == 1 and c[t] < hi:
                    sig[t] = -1; break
                if spiked == -1 and c[t] > lo:
                    sig[t] = 1; break
    return sig


def sig_news_breakout(df, atr, cfg):
    """News breakout: any high-impact release, first close beyond the pre-release hour."""
    return _event_signals(df, atr, cfg, None, "breakout")


def sig_news_reversal(df, atr, cfg):
    """News reversal: fade a 1.5 ATR release spike that closes back inside the pre-release range."""
    return _event_signals(df, atr, cfg, None, "reversal")


def sig_nfp(df, atr, cfg):
    """Non-Farm Payrolls breakout (dates generated by rule + calendar)."""
    return _event_signals(df, atr, cfg, _NFP, "breakout")


def sig_cpi(df, atr, cfg):
    """CPI breakout (dates from the news calendar)."""
    return _event_signals(df, atr, cfg, _CPI, "breakout")


def sig_fomc(df, atr, cfg):
    """FOMC decision / press conference: fade the first spike (whipsaw is typical)."""
    return _event_signals(df, atr, cfg, _FOMC, "reversal")


def sig_rate_decision(df, atr, cfg):
    """Interest-rate decisions (any central bank in the calendar): breakout."""
    return _event_signals(df, atr, cfg, _RATES, "breakout")


GENERATORS = {
    "news_breakout": sig_news_breakout, "news_reversal": sig_news_reversal, "nfp": sig_nfp,
    "cpi": sig_cpi, "fomc": sig_fomc, "rate_decision": sig_rate_decision,
}
